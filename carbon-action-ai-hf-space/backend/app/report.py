"""Emissions and verified-savings report for management and buyers (PDF)."""
from __future__ import annotations

from datetime import datetime, timedelta

import pandas as pd

from .pdf import Pdf

H = 5 / 60  # hours per reading


def _num(v, d=1) -> str:
    return "-" if v is None or pd.isna(v) else f"{v:,.{d}f}"


def build(fr, days: int = 30) -> bytes:
    fac = fr.fac
    now = pd.Timestamp(fr.now)
    start = now - pd.Timedelta(days=days)
    df = fr.df[fr.df["timestamp"] > start]
    pdf = Pdf()
    is_sim = fr.sim.kind == "simulator"

    pdf.text(45, pdf.y - 8, "Emissions & Verified Savings Report", 18, True)
    pdf.y -= 28
    pdf.text(45, pdf.y, f"{fac['name']}, {fac['location']}  |  {fac['industry']}", 10.5)
    pdf.y -= 14
    pdf.text(45, pdf.y, f"Period: {start:%d %b %Y} to {now:%d %b %Y}  |  Generated by Carbon-Action AI", 9,
             color=(0.33, 0.39, 0.44))
    pdf.y -= 8
    if is_sim:
        pdf.para("Data source: SIMULATED PLANT. All readings and savings below come from the physics-based "
                 "simulator, not from real meters. Emission factors, caps and prices are illustrative placeholders.",
                 9, (0.7, 0.15, 0.15))
    else:
        pdf.para(f"Data source: uploaded file '{fr.sim.name}'. Emission factors, caps and prices are "
                 "the values in the site configuration and should be confirmed before external use.", 9,
                 (0.7, 0.15, 0.15))

    # summary --------------------------------------------------------------
    direct = float(df["co2_direct_kg_h"].sum() * H / 1000)
    indirect = float(df["co2_indirect_kg_h"].sum() * H / 1000)
    total = direct + indirect
    prod = float(df[df["machine_type"] == "stenter"]["production_kg_h"].sum() * H / 1000)
    cap = fac["rolling_30d_cap_t_co2"] * days / 30
    pdf.heading("Summary")
    pdf.table(["Measure", "Value", "Note"], [
        ["Scope 1: direct CO2 (fuel burned)", f"{_num(direct)} t", "Boiler fuel and stenter gas"],
        ["Scope 2: indirect CO2 (electricity)", f"{_num(indirect)} t", f"Grid factor {fac['grid_factor_kg_per_kwh']} kg CO2/kWh"],
        ["Total CO2", f"{_num(total)} t", f"{total / cap * 100:.0f}% of the {cap:,.0f} t budget"],
        ["Fabric produced", f"{_num(prod)} t", ""],
        ["CO2 intensity", f"{total / prod:.2f} kg CO2 per kg fabric" if prod else "-", ""],
    ], [0.42, 0.26, 0.32])

    # daily chart ----------------------------------------------------------
    daily = df.groupby(df["timestamp"].dt.normalize())["co2_kg_h"].sum() * H / 1000
    daily = daily[daily.index < now.normalize()]
    if len(daily):
        pdf.heading("Daily CO2 (t)")
        pdf.bars([d.strftime("%d %b") for d in daily.index], [float(v) for v in daily.values],
                 cap=fac["daily_cap_t_co2"])
        over = int((daily > fac["daily_cap_t_co2"]).sum())
        pdf.para(f"{over} of {len(daily)} complete days were above the daily cap of {fac['daily_cap_t_co2']:g} t.")

    # by machine -------------------------------------------------------------
    rows = []
    for m in fac["machines"]:
        g = df[df["machine_id"] == m["id"]]
        sensor = len(fr.sensor_issues(m["id"]))
        rows.append([m["name"], f"{_num(g['co2_kg_h'].sum() * H / 1000)} t",
                     f"{_num(g['fuel_rate'].sum() * H, 0)} {m['fuel_unit']}", f"{_num(g['electricity_kw'].sum() * H / 1000)} MWh",
                     f"{sensor} open" if sensor else "OK"])
    pdf.heading("By machine")
    pdf.table(["Machine", "CO2", "Fuel", "Electricity", "Instruments"], rows, [0.36, 0.14, 0.2, 0.16, 0.14])

    # savings ----------------------------------------------------------------
    sv = fr.savings()
    verified = [a for a in fr.actions if a["status"] == "Verified"]
    pdf.heading("Verified savings")
    pdf.table(["Measure", "Value"], [
        ["CO2 avoided (counted so far)", f"{sv['co2_avoided_t']:,.2f} t"],
        ["Money saved on fuel and power (counted so far)", f"Rs {sv['inr_saved']:,.0f}"],
        ["Still being saved now", f"{sv['co2_t_per_day_now']:,.2f} t CO2 per day"],
        ["Actions verified by measurement", str(len(verified))],
    ], [0.65, 0.35])
    pdf.para("Method: a saving is the CO2 the machine would have emitted after the change at its earlier settings "
             "(adjusted baseline from the digital twin), minus the CO2 actually measured. It is counted from when the "
             "work was done, for a limited period per action, and stops if the same problem returns.")

    # decisions --------------------------------------------------------------
    pdf.heading("Decisions and work orders")
    if fr.actions:
        rows = [[f"{datetime.fromisoformat(a['decided_at']):%d %b %H:%M}", a["machine_id"], a["title"], a["status"],
                 a.get("assignee") or "-", f"{a['predicted_kg_h']:.1f}" if a.get("predicted_kg_h") is not None else "-",
                 f"{a['actual_kg_h']:.1f}" if a.get("actual_kg_h") is not None else "-",
                 f"{a['accuracy_pct']:.0f}%" if a.get("accuracy_pct") is not None else "-"]
                for a in reversed(fr.actions)]
        pdf.table(["Decided", "Machine", "Action", "Status", "Assigned to", "Pred.", "Actual", "Acc."],
                  rows, [0.13, 0.09, 0.29, 0.13, 0.14, 0.08, 0.08, 0.06], 7.5)
    else:
        pdf.para("No decisions in this period.")

    # alerts -----------------------------------------------------------------
    since = (now - timedelta(days=days)).isoformat()
    alerts = [a for a in fr.alerts if a["time"] >= since]
    pdf.heading("Alerts")
    kinds = {"anomaly": "Process anomalies", "sensor": "Instrument problems"}
    counts: dict[str, int] = {}
    for a in alerts:
        name = kinds.get(a["kind"], "Cap warnings")
        counts[name] = counts.get(name, 0) + 1
    if counts:
        pdf.table(["Type", "Count"], [[k, v] for k, v in counts.items()], [0.7, 0.3])
    else:
        pdf.para("No alerts in this period.")

    pdf.heading("How the numbers are calculated", 11)
    pdf.para("CO2 from coal = coal burned x carbon fraction x 44/12 x 0.98. CO2 from gas = gas burned x site emission "
             "factor. CO2 from electricity = kWh x grid factor. Readings are at 5-minute intervals.")
    return pdf.bytes(f"Carbon-Action AI  |  {fac['name']}  |  {now:%d %b %Y}")
